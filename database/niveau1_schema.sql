CREATE TABLE plat_du_jour (
    id SERIAL PRIMARY KEY,
    id_plat INT NOT NULL REFERENCES plat(id) ON DELETE CASCADE,
    date_jour DATE NOT NULL,
    UNIQUE (id_plat, date_jour)
);